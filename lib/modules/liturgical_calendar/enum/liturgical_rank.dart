/// The LiturgicalRank enum represents the different ranks of liturgical 
/// celebrations in the Christian liturgical calendar. 
/// Each rank indicates the level of solemnity and importance of the celebration, 
/// with "solemnity" being the highest rank and "optionalMemorial" being the lowest.
enum LiturgicalRank {
  solemnity,
  feastOfTheLord,
  feast,
  memorial,
  optionalMemorial
}