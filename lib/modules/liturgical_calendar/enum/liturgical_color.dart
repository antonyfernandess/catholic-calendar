/// An enumeration of the liturgical colors used in the liturgical calendar.
/// Each color represents a specific liturgical season or celebration, 
/// and is used in vestments, altar decorations, 
/// and other liturgical items to signify the mood and theme of the celebration.
enum LiturgicalColor {
  white, //Used during the seasons of Christmas and Easter, Feasts and Solemnities of the Lord, the Blessed Virgin Mary, the angels, and saints who were not martyrs.
  green, // Used during Ordinary Time.
  red, // Used on Palm Sunday, Good Friday, Pentecost, for the feasts of martyrs and apostles, and for the celebrations of the Holy Cross and the Sacred Heart
  rose, // Only used on Gaudete Sunday (3rd Sunday of Advent) and Laetare Sunday (4th Sunday of Lent).
  violet, // Used during the seasons of Advent and Lent, and for the Sacrament of Reconciliation.
}